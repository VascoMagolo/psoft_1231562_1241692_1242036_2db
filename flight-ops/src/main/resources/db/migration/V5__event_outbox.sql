-- Events waiting to be published on RabbitMQ (transactional outbox, Assignment 2): written in the
-- transaction of the change they describe, removed once the broker confirms them (EventRelay).
-- Only used when aisafe.events.enabled=true.
CREATE TABLE event_outbox (
    id bigint generated by default as identity,
    exchange varchar(255) not null,
    routing_key varchar(255) not null,
    body clob not null,
    correlation_id varchar(255),
    created_at timestamp(6) with time zone not null,
    attempts integer not null,
    last_error varchar(500),
    primary key (id)
);
